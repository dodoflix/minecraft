#!/usr/bin/env bash
# `/locate` parity for every structure and every biome: the same `locate structure` / `locate biome` commands on the real vanilla
# server and on ours with the same seed (scripts/command-diff.sh, one pair of servers per seed), answers compared per command.
#
#   scripts/worldgen-locate-diff.sh SEED... [-- command-diff.sh options]
#
# The command list is built from the vanilla registry export (ref/generated): every structure and every biome, searched in the
# dimension it belongs to from (0, 64, 0). The corpus of a seed lands in run/locate-diff/<seed>.txt. Exit status: the worst of
# the command-diff runs.
# Needs: ref/ (scripts/setup-ref.sh), MC_ACCEPT_EULA=1.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=scripts/lib.sh
. "$ROOT/scripts/lib.sh"
help_flag "$@"
seeds=()
while [[ $# -gt 0 && $1 != -- ]]; do seeds+=("$1"); shift; done
[[ $# -gt 0 ]] && shift
[[ ${#seeds[@]} -gt 0 ]] || die "no seed given"
WG="$ROOT/ref/generated/data/minecraft/worldgen"
[[ -d $WG/structure ]] || die "$WG/structure missing: run scripts/setup-ref.sh"
dim_of() {   # dim_of NAME -> the dimension a structure or biome belongs to
  case "$1" in
    fortress | bastion_remnant | nether_fossil | ruined_portal_nether | nether_wastes | soul_sand_valley | crimson_forest | warped_forest | basalt_deltas) echo the_nether ;;
    end_city | the_end | small_end_islands | end_midlands | end_highlands | end_barrens) echo the_end ;;
    *) echo overworld ;;
  esac
}
status=0
for seed in "${seeds[@]}"; do
  corpus="$ROOT/run/locate-diff/$seed.txt"
  mkdir -p "$(dirname "$corpus")"
  {
    echo "# generated by scripts/worldgen-locate-diff.sh"
    echo "!world normal structures"
    for kind in structure biome; do
      for f in "$WG/$kind"/*.json; do
        n="$(basename "$f" .json)"
        echo "execute in minecraft:$(dim_of "$n") positioned 0 64 0 run locate $kind minecraft:$n"
      done
    done
  } >"$corpus"
  "$ROOT/scripts/command-diff.sh" "$corpus" --seed "$seed" "$@" || status=$?
done
exit "$status"
