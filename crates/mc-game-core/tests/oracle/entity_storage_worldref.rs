//! The entities of the vanilla reference world go through the level: loaded with their chunks, stored by a flushed save,
//! and the entity region files equal what vanilla wrote (same chunks, same entities in the same order).

use super::chunk_world::{copy_dir, open_level, world_dimension_dir};
use mc_core::ident::Identifier;
use mc_core::pos::chunk_pos::ChunkPos;
use mc_nbt::CompoundTag;
use mc_world::region::{EntityStorage, RegionStorageInfo, SimpleRegionStorage};
use std::collections::BTreeMap;
use std::path::Path;
use std::time::{Duration, Instant};

/// Every non-empty chunk of the entity region files of `dir`, by position.
fn stored_chunks(dir: &Path) -> BTreeMap<(i32, i32), Vec<CompoundTag>> {
    let mut storage = EntityStorage::new(SimpleRegionStorage::new(
        RegionStorageInfo::new(
            "test",
            Identifier::parse("minecraft:overworld").unwrap(),
            "entities",
        ),
        dir.join("entities"),
        false,
    ));
    let mut out = BTreeMap::new();
    for rx in -2..2 {
        for rz in -2..2 {
            if !dir.join(format!("entities/r.{rx}.{rz}.mca")).exists() {
                continue;
            }
            for lx in 0..32 {
                for lz in 0..32 {
                    let pos = ChunkPos::new(rx * 32 + lx, rz * 32 + lz);
                    let loaded = storage.load_entities(&pos).unwrap();
                    if !loaded.chunk.is_empty() {
                        out.insert((pos.x, pos.z), loaded.chunk.get_entities().to_vec());
                    }
                }
            }
        }
    }
    out
}

#[test]
#[ignore = "oracle: needs the vanilla reference world (generated by mc_testkit::worldref)"]
fn worldref_entity_chunks_survive_a_level_save() {
    let tmp = tempfile::tempdir().unwrap();
    copy_dir(&world_dimension_dir(), tmp.path());
    let vanilla = stored_chunks(tmp.path());
    assert!(!vanilla.is_empty(), "the reference world has entities");

    let mut level = open_level(tmp.path());
    for &(x, z) in vanilla.keys() {
        level
            .chunk_source
            .update_chunk_forced(ChunkPos::new(x, z), true);
    }
    let start = Instant::now();
    loop {
        level.poll_chunk_task();
        level.tick_chunk_source(&|| true, false, true);
        level.tick_entity_management();
        if vanilla.keys().all(|&(x, z)| {
            level.chunk_now(x, z).is_some()
                && level
                    .entity_manager
                    .are_entities_loaded(ChunkPos::new(x, z).pack())
        }) {
            break;
        }
        assert!(start.elapsed() < Duration::from_secs(120), "chunks load");
        std::thread::sleep(Duration::from_millis(1));
    }
    let loaded: usize = vanilla.values().map(Vec::len).sum();
    assert!(level.entity_manager.get_all().count() >= loaded);

    // age the files, so that only a write by the level can make them look fresh
    let old = std::time::SystemTime::UNIX_EPOCH;
    let files: Vec<_> = std::fs::read_dir(tmp.path().join("entities"))
        .unwrap()
        .map(|e| e.unwrap().path())
        .collect();
    for file in &files {
        std::fs::File::options()
            .write(true)
            .open(file)
            .unwrap()
            .set_modified(old)
            .unwrap();
    }
    level.save(true);
    for file in &files {
        assert!(
            std::fs::metadata(file).unwrap().modified().unwrap() > old,
            "{file:?} was written by the save"
        );
    }
    let ours = stored_chunks(tmp.path());
    level.close();
    assert_eq!(
        ours.keys().collect::<Vec<_>>(),
        vanilla.keys().collect::<Vec<_>>(),
        "the chunks that hold entities"
    );
    for (pos, tags) in &vanilla {
        assert_eq!(&ours[pos], tags, "entities of chunk {pos:?}");
    }
}
