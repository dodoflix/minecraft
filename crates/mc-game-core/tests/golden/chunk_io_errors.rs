//! A chunk, entity chunk or points-of-interest chunk that cannot be read from its region file loads empty (entities: never
//! loads) and leaves `debug/chunk-<level>-<time>-server.txt` with the "Chunk Info" category; one that cannot be written is
//! reported as a save failure; a chunk stored at the wrong position is reported as misplaced; one saved by a version older
//! than the data fixer chain covers fails to load the same way as one whose data fix throws. Every report is also a
//! suppressed exception of the server.

use super::entity_persistence::{PIG, load_chunk, open_with, run_until, spawn};
use mc_core::ident::Identifier;
use mc_core::pos::{BlockPos, ChunkPos};
use mc_game::server::level::ServerLevel;
use mc_game::server::shared::ServerShared;
use mc_game::world::entity::ai::village::poi::PoiTypeHolder;
use mc_world::region::{RegionStorageInfo, SimpleRegionStorage};
use std::io::{Read, Seek, SeekFrom, Write};
use std::path::Path;
use std::sync::Arc;
use std::time::{Duration, Instant};

const LEVEL_ID: &str = "entities";

/// A server whose reports go to `debug` and whose disk is always low.
fn reporting_shared(debug: &Path) -> Arc<ServerShared> {
    let (shared, _rx) = ServerShared::new();
    shared.bind_game_thread();
    shared.chunk_io_reporter.set_debug_dir(debug.to_path_buf());
    shared.chunk_io_reporter.set_low_disk_space_check(|| true);
    shared
}

/// Stores chunk `pos` (generated by the void generator) with a pig and a home point of interest, and closes the level.
fn store_chunk(dir: &Path, pos: ChunkPos) {
    let (shared, _rx) = ServerShared::new();
    shared.bind_game_thread();
    let mut level = open_with(dir, shared);
    load_chunk(&mut level, pos);
    populate(&mut level, pos);
    level.save(true);
    level.close();
}

/// A pig (an entity chunk) and a home (a points-of-interest chunk) in chunk `pos`.
fn populate(level: &mut ServerLevel, pos: ChunkPos) {
    spawn(
        level,
        &PIG.replace("[8.5d,64.0d,8.5d]", "[56.5d,64.0d,56.5d]"),
    );
    level.chunk_source.chunk_map.poi_manager.add(
        BlockPos::new(pos.x * 16 + 8, 64, pos.z * 16 + 8),
        PoiTypeHolder::by_name("minecraft:home").unwrap(),
    );
}

/// Overwrites the first bytes of the compressed payload of chunk `pos` in its region file under `folder`.
fn corrupt_chunk(dir: &Path, folder: &str, pos: ChunkPos) {
    let file = dir
        .join(folder)
        .join(format!("r.{}.{}.mca", pos.x >> 5, pos.z >> 5));
    let mut f = std::fs::OpenOptions::new()
        .read(true)
        .write(true)
        .open(file)
        .unwrap();
    let index = u64::from((pos.x & 31) as u32 + (pos.z & 31) as u32 * 32);
    f.seek(SeekFrom::Start(index * 4)).unwrap();
    let mut entry = [0u8; 4];
    f.read_exact(&mut entry).unwrap();
    let sector = u64::from(u32::from_be_bytes(entry) >> 8);
    assert_ne!(sector, 0, "chunk {pos} is stored in {folder}");
    // 4 bytes length and 1 byte compression type precede the payload
    f.seek(SeekFrom::Start(sector * 4096 + 5)).unwrap();
    f.write_all(&[0xFF; 32]).unwrap();
}

/// Makes `folder` a file, so nothing can be stored in it.
fn block_folder(dir: &Path, folder: &str) {
    std::fs::write(dir.join(folder), b"not a folder").unwrap();
}

/// Whether the report writer left a file in `debug`.
fn has_report(debug: &Path) -> bool {
    std::fs::read_dir(debug).is_ok_and(|entries| entries.count() > 0)
}

/// The one report file of `debug/` (the reports are written on an IO thread).
fn only_report(debug: &Path) -> String {
    let start = Instant::now();
    loop {
        if let Ok(entries) = std::fs::read_dir(debug) {
            let files: Vec<_> = entries.map(|e| e.unwrap().path()).collect();
            if let Some(file) = files.first()
                && let Ok(text) = std::fs::read_to_string(file)
                && text.contains("-- Chunk Info --")
            {
                let name = file.file_name().unwrap().to_string_lossy().into_owned();
                assert!(
                    name.starts_with(&format!("chunk-{LEVEL_ID}-"))
                        && name.ends_with("-server.txt"),
                    "{name}"
                );
                return text;
            }
        }
        assert!(
            start.elapsed() < Duration::from_secs(10),
            "no report in {}",
            debug.display()
        );
        std::thread::sleep(Duration::from_millis(5));
    }
}

/// `pos`: the position the report names; `None` for a save, where the neighbours of the chunk fail as well and one of
/// their reports may be the one read.
fn assert_report(report: &str, description: &str, storage: &str, pos: Option<ChunkPos>) {
    assert!(
        report.starts_with("---- Minecraft Chunk IO Error Report ----\n// "),
        "{report}"
    );
    assert!(
        report.contains(&format!("\nDescription: {description}\n")),
        "{report}"
    );
    let position = pos.map_or("\tPosition: [".to_owned(), |p| format!("\tPosition: {p}\n"));
    assert!(
        report.contains(&format!(
            "-- Chunk Info --\nDetails:\n\tLevel: {LEVEL_ID}\n\tDimension: minecraft:overworld\n\tStorage: {storage}\n{position}"
        )),
        "{report}"
    );
}

fn reload(dir: &Path, debug: &Path, pos: ChunkPos) -> Arc<ServerShared> {
    let shared = reporting_shared(debug);
    let mut level = open_with(dir, shared.clone());
    load_chunk_without_entities(&mut level, pos);
    assert!(
        shared.chunk_io_reporter.take_ops_warning(),
        "the failure logs the low disk space warning and asks for the operators to be told"
    );
    level.close();
    shared
}

/// The chunk loads; its entities may not (a failed entity read leaves them pending).
fn load_chunk_without_entities(level: &mut ServerLevel, pos: ChunkPos) {
    level.chunk_source.update_chunk_forced(pos, true);
    run_until(level, |l| l.chunk_now(pos.x, pos.z).is_some());
}

fn suppressed(shared: &ServerShared) -> String {
    shared.suppressed_exceptions.dump()
}

#[test]
fn a_corrupt_chunk_loads_empty_and_is_reported() {
    let scratch = tempfile::tempdir().unwrap();
    let pos = ChunkPos::new(3, 3);
    store_chunk(scratch.path(), pos);
    corrupt_chunk(scratch.path(), "region", pos);
    let debug = scratch.path().join("debug");
    let shared = reload(scratch.path(), &debug, pos);
    assert_report(
        &only_report(&debug),
        "Chunk load failure",
        "chunk",
        Some(ChunkPos::new(3, 3)),
    );
    assert!(
        suppressed(&shared).contains("chunk/load:class java.util.zip.ZipException x 1\n"),
        "{}",
        suppressed(&shared)
    );
}

#[test]
fn a_chunk_stored_at_the_wrong_position_is_reported_as_misplaced() {
    let scratch = tempfile::tempdir().unwrap();
    store_chunk(scratch.path(), ChunkPos::new(3, 3));
    {
        // the chunk of (3, 3) copied into the slot of (4, 4)
        let mut storage = SimpleRegionStorage::new(
            RegionStorageInfo::new(
                LEVEL_ID,
                Identifier::parse("minecraft:overworld").unwrap(),
                "chunk",
            ),
            scratch.path().join("region"),
            false,
        );
        let tag = storage.read(&ChunkPos::new(3, 3)).unwrap().expect("stored");
        storage.write(&ChunkPos::new(4, 4), Some(tag));
        storage.close().unwrap();
    }
    let debug = scratch.path().join("debug");
    let shared = reload(scratch.path(), &debug, ChunkPos::new(4, 4));
    let report = only_report(&debug);
    assert!(
        report.contains("\nDescription: Chunk found in invalid location\n"),
        "{report}"
    );
    assert!(
        report.contains("-- Misplaced Chunk --\nDetails:\n\tStored Position: [3, 3]\n"),
        "{report}"
    );
    assert!(report.contains("\n\tPosition: [4, 4]\n"), "{report}");
    assert!(
        suppressed(&shared).contains("chunk/load:class net.minecraft.ReportedException x 1\n"),
        "{}",
        suppressed(&shared)
    );
}

/// Opens a level over `dir` whose `folder` cannot be written, makes `change` write into the chunk of (3, 3) and saves.
fn save_into_blocked_folder(
    folder: &str,
    write: impl FnOnce(&mut ServerLevel, ChunkPos),
) -> String {
    let scratch = tempfile::tempdir().unwrap();
    let pos = ChunkPos::new(3, 3);
    block_folder(scratch.path(), folder);
    let debug = scratch.path().join("debug");
    let shared = reporting_shared(&debug);
    let mut level = open_with(scratch.path(), shared.clone());
    load_chunk_without_entities(&mut level, pos);
    write(&mut level, pos);
    level.save(true);
    let report = only_report(&debug);
    assert!(
        suppressed(&shared).contains("chunk/save:class java.io.IOException x "),
        "{}",
        suppressed(&shared)
    );
    level.close();
    report
}

#[test]
fn a_chunk_that_cannot_be_written_is_reported() {
    let report = save_into_blocked_folder("region", |_, _| {});
    assert_report(&report, "Chunk save failure", "chunk", None);
}

#[test]
fn an_entity_chunk_that_cannot_be_written_is_reported() {
    let report = save_into_blocked_folder("entities", |level, pos| {
        run_until(level, |l| l.entity_manager.are_entities_loaded(pos.pack()));
        populate(level, pos);
    });
    assert_report(&report, "Chunk save failure", "entities", None);
}

#[test]
fn a_poi_chunk_that_cannot_be_written_is_reported() {
    let report = save_into_blocked_folder("poi", populate);
    assert_report(&report, "Chunk save failure", "poi", None);
}

#[test]
fn an_entity_chunk_that_cannot_be_read_is_reported() {
    let scratch = tempfile::tempdir().unwrap();
    let pos = ChunkPos::new(3, 3);
    store_chunk(scratch.path(), pos);
    corrupt_chunk(scratch.path(), "entities", pos);
    let debug = scratch.path().join("debug");
    let shared = reporting_shared(&debug);
    let mut level = open_with(scratch.path(), shared.clone());
    level.chunk_source.update_chunk_forced(pos, true);
    run_until(&mut level, |l| {
        l.chunk_now(pos.x, pos.z).is_some() && has_report(&debug)
    });
    assert!(
        !level.entity_manager.are_entities_loaded(pos.pack()),
        "a failed entity read leaves the entities pending"
    );
    assert_report(
        &only_report(&debug),
        "Chunk load failure",
        "entities",
        Some(pos),
    );
    assert!(
        suppressed(&shared).contains("chunk/load:class java.util.zip.ZipException x 1\n"),
        "{}",
        suppressed(&shared)
    );
    level.close();
}

#[test]
fn a_poi_chunk_that_cannot_be_read_is_reported() {
    let scratch = tempfile::tempdir().unwrap();
    let pos = ChunkPos::new(3, 3);
    store_chunk(scratch.path(), pos);
    corrupt_chunk(scratch.path(), "poi", pos);
    let debug = scratch.path().join("debug");
    let shared = reporting_shared(&debug);
    let mut level = open_with(scratch.path(), shared.clone());
    let home = BlockPos::new(56, 64, 56);
    assert_eq!(
        level.chunk_source.chunk_map.poi_manager.get_type(home),
        None,
        "the unreadable chunk has no points of interest"
    );
    assert_report(&only_report(&debug), "Chunk load failure", "poi", Some(pos));
    level.close();
}
