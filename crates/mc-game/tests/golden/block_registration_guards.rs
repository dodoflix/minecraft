/// (d) Every `BlockEntityType` has exactly one implementation, and every block that vanilla gives a block entity
/// (`newBlockEntity`) creates one.
#[test]
fn every_block_entity_type_and_block_has_an_implementation() {
    let types: Vec<_> = BlockEntityType::iter().collect();
    let mut problems = Vec::new();
    for ty in &types {
        match BLOCK_ENTITY_TYPES.iter().filter(|r| r.ty == *ty).count() {
            1 => {}
            n => problems.push(format!("{ty:?} has {n} registrations")),
        }
    }
    for (block, (name, java)) in Block::iter().zip(java_overrides()) {
        if java.iter().any(|(m, _)| *m == "newBlockEntity")
            && block != Block::MOVING_PISTON
            && new_block_entity(BlockPos::ZERO, block.default_state()).is_none()
        {
            problems.push(format!("{name} creates no block entity"));
        }
    }
    for ty in types {
        for block in ty.data().valid_blocks {
            if new_block_entity(BlockPos::ZERO, block.default_state()).is_none()
                && *block != Block::MOVING_PISTON
            {
                problems.push(format!(
                    "{} ({ty:?}) creates no block entity",
                    block.data().name
                ));
            }
        }
    }
    assert!(problems.is_empty(), "{problems:#?}");
}

/// Whether `quoted` occurs in `text` anywhere but inside a function carrying an `#[ignore]` attribute: an ignored golden never replays
/// its scenario.
fn quoted_outside_ignored_tests(text: &str, quoted: &str) -> bool {
    text.match_indices(quoted).any(|(at, _)| {
        let head = &text[..at];
        let Some(fn_at) = head.rfind("fn ") else {
            return true;
        };
        // the occurrence belongs to that function only while no top-level item closed in between
        if head[fn_at..].contains("\n}\n") {
            return true;
        }
        let line_start = head[..fn_at].rfind('\n').map_or(0, |i| i + 1);
        let attributes: Vec<&str> = head[..line_start]
            .lines()
            .rev()
            .take_while(|l| {
                let l = l.trim_start();
                l.starts_with("#[") || l.starts_with("///")
            })
            .collect();
        !attributes
            .iter()
            .any(|l| l.trim_start().starts_with("#[ignore"))
    })
}

#[test]
fn a_scenario_named_only_by_an_ignored_test_is_not_replayed() {
    let source = r#"
#[test]
fn replayed() {
    check("blk_a");
}

#[test]
#[ignore = "deviation"]
fn skipped() {
    check("blk_b");
}

/// docs
#[ignore]
#[test]
fn skipped_too() {
    check("blk_c");
}

#[test]
fn replayed_too() {
    check("blk_c");
}
"#;
    assert!(quoted_outside_ignored_tests(source, "\"blk_a\""));
    assert!(!quoted_outside_ignored_tests(source, "\"blk_b\""));
    assert!(quoted_outside_ignored_tests(source, "\"blk_c\""));
}

/// (e) Every `blk_*` scenario script has a recorded fixture and a replay test that names it (an `#[ignore]`d test does not count).
#[test]
fn every_block_scenario_has_a_fixture_and_a_replay() {
    let tests = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests");
    let mut sources = Vec::new();
    rust_files(&tests.join("golden"), &mut sources);
    let sources: Vec<String> = sources
        .iter()
        .map(|f| std::fs::read_to_string(f).expect("read a golden source"))
        .collect();
    // `concat!("blk_fluid_", stringify!(name))` macros: the prefix plus any identifier of the same file names a scenario
    let replayed = |scenario: &str| {
        sources.iter().any(|text| {
            quoted_outside_ignored_tests(text, &format!("\"{scenario}\""))
                || text.match_indices("concat!(\"blk_").any(|(at, _)| {
                    let rest = &text[at + "concat!(\"".len()..];
                    let prefix = &rest[..rest.find('"').unwrap_or(0)];
                    scenario.strip_prefix(prefix).is_some_and(|ident| {
                        let word = |c: char| c.is_alphanumeric() || c == '_';
                        text.match_indices(ident).any(|(at, _)| {
                            !text[..at].ends_with(word)
                                && !text[at + ident.len()..].starts_with(word)
                        })
                    })
                })
        })
    };
    let mut problems = Vec::new();
    let mut names: Vec<String> = std::fs::read_dir(tests.join("oracle/scenarios"))
        .expect("read the scenarios")
        .filter_map(|e| {
            let name = e.ok()?.file_name().into_string().ok()?;
            let stem = name.strip_suffix(".txt")?;
            stem.starts_with("blk_").then(|| stem.to_string())
        })
        .collect();
    names.sort();
    let fixtures = tests.join("fixtures/entity_oracle");
    for name in names {
        if !fixtures.join(format!("{name}.txt")).exists()
            && !fixtures.join(format!("{name}.txt.gz")).exists()
        {
            problems.push(format!("{name}: no fixture"));
        }
        if !replayed(&name) {
            problems.push(format!("{name}: no replay test"));
        }
    }
    assert!(problems.is_empty(), "{problems:#?}");
}

