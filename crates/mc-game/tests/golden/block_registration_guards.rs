/// Everything the guards need from the Rust sources.
struct Source {
    trait_methods: BTreeSet<String>,
    /// Type ident -> the `BlockBehaviour` methods its impls define (macros expanded by name).
    impls: BTreeMap<String, BTreeSet<String>>,
    /// Vanilla class simple name -> the Rust type its registration constructs.
    classes: BTreeMap<String, String>,
    /// Block registry name -> the Rust type its by-name registration constructs.
    blocks: BTreeMap<String, String>,
    /// Registrations whose type the scan could not read.
    unresolved: Vec<String>,
}

/// One arm of a `macro_rules!`: its matcher, the `fn`s it defines and the macros it calls (name, arguments).
struct Arm {
    matcher: String,
    fns: BTreeSet<String>,
    calls: Vec<(String, String)>,
}

struct MacroDef {
    arms: Vec<Arm>,
    /// An arm expands to a whole `impl BlockBehaviour for $type`.
    whole_impl: bool,
}

/// An impl: (type, fn names, macro calls inside it as (name, arguments), file).
type ImplEntry = (String, BTreeSet<String>, Vec<(String, String)>, PathBuf);

/// A `macro!(Type, ..)` item: (macro, first token, arguments, fn names in the arguments, file).
type ItemInvocation = (String, String, String, BTreeSet<String>, PathBuf);

#[derive(Default)]
struct Scan {
    macros: BTreeMap<String, MacroDef>,
    impls: Vec<ImplEntry>,
    /// Item level macro invocations, the ones that expand to a whole impl are used.
    item_macros: Vec<ItemInvocation>,
    fn_returns: BTreeMap<String, BTreeSet<String>>,
    /// (is by-name, key, tokens of the constructor closure)
    registrations: Vec<(bool, String, Vec<String>)>,
}

/// The `fn` names and the macro calls `name!(args)` (name, arguments) of a token list.
fn fns_and_calls(w: &[String]) -> (BTreeSet<String>, Vec<(String, String)>) {
    let mut fns = BTreeSet::new();
    let mut calls = Vec::new();
    for (i, word) in w.iter().enumerate() {
        if word == "fn"
            && let Some(n) = w.get(i + 1)
        {
            fns.insert(n.clone());
        }
        if w.get(i + 1).is_some_and(|n| n == "!")
            && w.get(i + 2)
                .is_some_and(|n| matches!(n.as_str(), "(" | "{" | "["))
        {
            let mut depth = 0;
            let mut end = i + 2;
            for (j, t) in w.iter().enumerate().skip(i + 2) {
                match t.as_str() {
                    "(" | "{" | "[" => depth += 1,
                    ")" | "}" | "]" => {
                        depth -= 1;
                        if depth == 0 {
                            end = j;
                            break;
                        }
                    }
                    _ => {}
                }
            }
            calls.push((
                word.clone(),
                w.get(i + 3..end).unwrap_or_default().join(" "),
            ));
        }
    }
    (fns, calls)
}

/// The arms `(matcher) => { body };` of a `macro_rules!` body.
fn macro_arms(tokens: &proc_macro2::TokenStream) -> Vec<Arm> {
    use proc_macro2::TokenTree;
    let trees: Vec<TokenTree> = tokens.clone().into_iter().collect();
    let mut arms = Vec::new();
    let mut i = 0;
    while let (
        Some(TokenTree::Group(matcher)),
        Some(TokenTree::Punct(_)),
        Some(TokenTree::Punct(_)),
        Some(TokenTree::Group(body)),
    ) = (
        trees.get(i),
        trees.get(i + 1),
        trees.get(i + 2),
        trees.get(i + 3),
    ) {
        let (fns, calls) = fns_and_calls(&words(&body.stream()));
        arms.push(Arm {
            matcher: words(&matcher.stream()).join(" "),
            fns,
            calls,
        });
        i += 4;
        if matches!(trees.get(i), Some(TokenTree::Punct(p)) if p.as_char() == ';') {
            i += 1;
        }
    }
    arms
}

/// The tokens of a macro invocation, flattened: idents, literals, single punctuation characters and group delimiters
/// (`proc_macro2`'s `to_string` glues `(Type)` together).
fn words(tokens: &proc_macro2::TokenStream) -> Vec<String> {
    use proc_macro2::{Delimiter, TokenTree};
    let mut out = Vec::new();
    for tree in tokens.clone() {
        match tree {
            TokenTree::Group(g) => {
                let (open, close) = match g.delimiter() {
                    Delimiter::Parenthesis => ("(", ")"),
                    Delimiter::Brace => ("{", "}"),
                    Delimiter::Bracket => ("[", "]"),
                    Delimiter::None => ("", ""),
                };
                out.push(open.to_string());
                out.extend(words(&g.stream()));
                out.push(close.to_string());
            }
            TokenTree::Punct(p) => out.push(p.as_char().to_string()),
            tree => out.push(tree.to_string()),
        }
    }
    out
}

fn last_ident(path: &syn::Path) -> String {
    path.segments
        .last()
        .map_or_else(String::new, |s| s.ident.to_string())
}

fn is_cfg_test(attrs: &[syn::Attribute]) -> bool {
    attrs.iter().any(|a| {
        a.path().is_ident("cfg")
            && a.meta
                .require_list()
                .is_ok_and(|l| l.tokens.to_string() == "test")
    })
}

impl Scan {
    fn items(&mut self, items: &[syn::Item], file: &Path) {
        for item in items {
            match item {
                syn::Item::Mod(m) if !is_cfg_test(&m.attrs) => {
                    if let Some((_, items)) = &m.content {
                        self.items(items, file);
                    }
                }
                syn::Item::Fn(f) => {
                    if let syn::ReturnType::Type(_, ty) = &f.sig.output
                        && let syn::Type::Path(p) = &**ty
                    {
                        self.fn_returns
                            .entry(f.sig.ident.to_string())
                            .or_default()
                            .insert(last_ident(&p.path));
                    }
                }
                syn::Item::Impl(i) => {
                    let Some((trait_path, _)) = &i.trait_ else {
                        continue;
                    };
                    let syn::Type::Path(self_ty) = &*i.self_ty else {
                        continue;
                    };
                    if last_ident(trait_path) != "BlockBehaviour" {
                        continue;
                    }
                    let mut fns = BTreeSet::new();
                    let mut calls = Vec::new();
                    for it in &i.items {
                        match it {
                            syn::ImplItem::Fn(f) => {
                                fns.insert(f.sig.ident.to_string());
                            }
                            syn::ImplItem::Macro(m) => {
                                calls.push((
                                    last_ident(&m.mac.path),
                                    words(&m.mac.tokens).join(" "),
                                ));
                            }
                            _ => {}
                        }
                    }
                    self.impls
                        .push((last_ident(&self_ty.path), fns, calls, file.to_path_buf()));
                }
                syn::Item::Macro(m) => self.item_macro(m, file),
                _ => {}
            }
        }
    }

    fn item_macro(&mut self, m: &syn::ItemMacro, file: &Path) {
        let name = last_ident(&m.mac.path);
        let w = words(&m.mac.tokens);
        match name.as_str() {
            "macro_rules" => {
                let Some(ident) = &m.ident else { return };
                let whole_impl = w.windows(3).any(|x| x == ["impl", "BlockBehaviour", "for"]);
                let arms = macro_arms(&m.mac.tokens);
                assert!(!arms.is_empty(), "macro `{ident}` has no readable arm");
                self.macros
                    .insert(ident.to_string(), MacroDef { arms, whole_impl });
            }
            "register_block_class" | "register_block" => {
                let key = w[0].trim_matches('"').to_string();
                self.registrations
                    .push((name == "register_block", key, w[1..].to_vec()));
            }
            _ => {
                if let Some(first) = w.first() {
                    let (fns, _) = fns_and_calls(&w);
                    self.item_macros.push((
                        name,
                        first.clone(),
                        w.join(" "),
                        fns,
                        file.to_path_buf(),
                    ));
                }
            }
        }
    }

    /// The `fn` names the arm of a macro that matches `args` defines, nested macro calls included. `args` that no arm
    /// matches literally select the arms with a `$` matcher.
    fn macro_fns(
        &self,
        name: &str,
        args: &str,
        seen: &mut BTreeSet<(String, String)>,
    ) -> BTreeSet<String> {
        let mut out = BTreeSet::new();
        let Some(def) = self.macros.get(name) else {
            return out;
        };
        if !seen.insert((name.to_string(), args.to_string())) {
            return out;
        }
        let mut arms: Vec<&Arm> = def.arms.iter().filter(|a| a.matcher == args).collect();
        if arms.is_empty() {
            arms = def
                .arms
                .iter()
                .filter(|a| a.matcher.contains('$'))
                .collect();
        }
        for arm in arms {
            out.extend(arm.fns.iter().cloned());
            for (call, call_args) in &arm.calls {
                out.extend(self.macro_fns(call, call_args, seen));
            }
        }
        out
    }

    /// `Box::new(Type { .. })`, `Box::new(Type::new(..))`, `Box::new(helper(..))` -> `Type`.
    fn registered_type(&self, tokens: &[String]) -> Option<String> {
        let mut start = tokens
            .windows(5)
            .position(|w| w == ["Box", ":", ":", "new", "("])?
            + 5;
        // `Box::new(match block.data().name { "minecraft:x" => Type { .. }, .. })`: the type of the first arm
        if tokens.get(start).is_some_and(|w| w == "match") {
            start += tokens[start..].windows(2).position(|w| w == ["=", ">"])? + 2;
        }
        let mut path = Vec::new();
        let mut i = start;
        while let Some(w) = tokens.get(i) {
            path.push(w.clone());
            if tokens.get(i + 1).is_some_and(|n| n == ":")
                && tokens.get(i + 2).is_some_and(|n| n == ":")
            {
                i += 3;
            } else {
                break;
            }
        }
        if let Some(ty) = path
            .iter()
            .rev()
            .find(|w| w.starts_with(|c: char| c.is_ascii_uppercase()))
        {
            return Some(ty.clone());
        }
        let returns = self.fn_returns.get(path.last()?)?;
        (returns.len() == 1)
            .then(|| returns.iter().next().cloned())
            .flatten()
    }
}

pub(crate) fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) {
    for entry in std::fs::read_dir(dir).expect("read the source directory") {
        let path = entry.expect("directory entry").path();
        if path.is_dir() {
            rust_files(&path, out);
        } else if path.extension().is_some_and(|e| e == "rs") {
            out.push(path);
        }
    }
}

static SOURCE: LazyLock<Source> = LazyLock::new(|| {
    let crates = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let mut files = Vec::new();
    for entry in std::fs::read_dir(&crates).expect("read crates/") {
        let src = entry.expect("crate directory").path().join("src");
        if src.is_dir() {
            rust_files(&src, &mut files);
        }
    }
    files.sort();
    let mut scan = Scan::default();
    let mut trait_methods = BTreeSet::new();
    for file in &files {
        let text = std::fs::read_to_string(file).expect("read a source file");
        if !(text.contains("BlockBehaviour") || text.contains("register_block")) {
            continue;
        }
        let parsed = syn::parse_file(&text).unwrap_or_else(|e| panic!("{}: {e}", file.display()));
        for item in &parsed.items {
            if let syn::Item::Trait(t) = item
                && t.ident == "BlockBehaviour"
            {
                for ti in &t.items {
                    if let syn::TraitItem::Fn(f) = ti {
                        trait_methods.insert(f.sig.ident.to_string());
                    }
                }
            }
        }
        scan.items(&parsed.items, file);
    }
    assert!(
        !trait_methods.is_empty(),
        "the BlockBehaviour trait was not found"
    );

    let mut impls: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let mut impl_files: BTreeMap<String, BTreeSet<PathBuf>> = BTreeMap::new();
    for (ty, fns, calls, file) in &scan.impls {
        let set = impls.entry(ty.clone()).or_default();
        set.extend(fns.iter().cloned());
        for (call, args) in calls {
            set.extend(scan.macro_fns(call, args, &mut BTreeSet::new()));
        }
        impl_files
            .entry(ty.clone())
            .or_default()
            .insert(file.clone());
    }
    for (name, first, args, extra_fns, file) in &scan.item_macros {
        if scan.macros.get(name).is_some_and(|d| d.whole_impl) {
            let set = impls.entry(first.clone()).or_default();
            set.extend(scan.macro_fns(name, args, &mut BTreeSet::new()));
            set.extend(extra_fns.iter().cloned());
            impl_files
                .entry(first.clone())
                .or_default()
                .insert(file.clone());
        }
    }
    for (ty, files) in &impl_files {
        assert!(
            files.len() == 1,
            "type `{ty}` implements BlockBehaviour in several files, the guards cannot tell them apart: {files:?}"
        );
    }
    for set in impls.values_mut() {
        set.retain(|m| trait_methods.contains(m));
    }

    let mut classes = BTreeMap::new();
    let mut blocks = BTreeMap::new();
    let mut unresolved = Vec::new();
    for (by_name, key, tokens) in &scan.registrations {
        match scan.registered_type(tokens) {
            Some(ty) => {
                let map = if *by_name { &mut blocks } else { &mut classes };
                assert!(
                    map.insert(key.clone(), ty).is_none(),
                    "`{key}` is registered twice"
                );
            }
            None => unresolved.push(key.clone()),
        }
    }
    Source {
        trait_methods,
        impls,
        classes,
        blocks,
        unresolved,
    }
});

impl Source {
    /// The type the block's behaviour is (`behaviour::build`: by-name registration, then the class chain), and the
    /// class chain position it came from.
    fn bound(&self, block: Block) -> (&str, Option<usize>) {
        let data = block.data();
        if let Some(ty) = self.blocks.get(data.name) {
            return (ty, None);
        }
        for (i, class) in data.classes.iter().enumerate() {
            if let Some(ty) = self.classes.get(*class) {
                return (ty, Some(i));
            }
        }
        ("PlainBlock", Some(data.classes.len()))
    }

    fn methods(&self, ty: &str) -> BTreeSet<String> {
        self.impls.get(ty).cloned().unwrap_or_default()
    }
}

/// Fails with the problems that are not in `accepted` (`key`, reason: a known gap with its owner) and with the accepted
/// keys that no longer occur, so the lists only ever shrink.
fn report(what: &str, mut failures: BTreeMap<String, Vec<String>>, accepted: &[(&str, &str)]) {
    let mut stale = Vec::new();
    for (key, _) in accepted {
        if failures.remove(*key).is_none() {
            stale.push(*key);
        }
    }
    if failures.is_empty() && stale.is_empty() {
        return;
    }
    let mut text = format!("{what}: {} problem(s)\n", failures.len());
    for (key, blocks) in &failures {
        let shown: Vec<_> = blocks.iter().take(4).cloned().collect();
        text += &format!(
            "  {key}: {} block(s), e.g. {}{}\n",
            blocks.len(),
            shown.join(", "),
            if blocks.len() > shown.len() {
                ", ..."
            } else {
                ""
            }
        );
    }
    for key in stale {
        text += &format!("  accepted but no longer a problem, delete it: {key}\n");
    }
    panic!("{text}");
}

#[test]
fn every_registration_resolves_to_a_behaviour_impl() {
    let src = &*SOURCE;
    assert_eq!(
        src.classes.len() + src.blocks.len() + src.unresolved.len(),
        BLOCK_CLASSES.len() + BLOCKS.len(),
        "the source scan found a different number of registrations than the linked registry"
    );
    assert!(
        src.unresolved.is_empty(),
        "registrations whose type the scan cannot read: {:?}",
        src.unresolved
    );
    let missing: Vec<_> = src
        .classes
        .iter()
        .chain(&src.blocks)
        .filter(|(_, ty)| *ty != "PlainBlock" && !src.impls.contains_key(*ty))
        .collect();
    assert!(
        missing.is_empty(),
        "types without a BlockBehaviour impl: {missing:?}"
    );
}

/// (a) Shadow guard: the bound class overrides a superset of what every registered ancestor class overrides.
#[test]
fn registered_subclasses_override_what_their_registered_ancestors_override() {
    let src = &*SOURCE;
    let mut failures: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for block in Block::iter() {
        let data = block.data();
        let (bound, at) = src.bound(block);
        let own = src.methods(bound);
        for (j, class) in data.classes.iter().enumerate() {
            if at.is_some_and(|i| j <= i) {
                continue;
            }
            let Some(ancestor) = src.classes.get(*class) else {
                continue;
            };
            let missing: Vec<_> = src
                .methods(ancestor)
                .difference(&own)
                .filter(|m| !REDUNDANT.contains(&m.as_str()))
                .cloned()
                .collect();
            if !missing.is_empty() {
                failures
                    .entry(format!(
                        "{bound} lacks {} of its ancestor {class} ({ancestor})",
                        missing.join("/")
                    ))
                    .or_default()
                    .push(data.name.to_string());
            }
        }
    }
    report("shadowed ancestor overrides", failures, ACCEPTED_SHADOWS);
}

/// A Java override: `(method, declaring class)`.
type Override = (&'static str, &'static str);

/// Overrides the Rust port handles without a trait method override of the registered class: (declaring class, with a
/// trailing `*` for a prefix; method; why).
const GENERIC: &[(&str, &str, &str)] = &[
    (
        "BaseEntityBlock",
        "triggerEvent",
        "forwarded to the block entity by the block event dispatch",
    ),
    (
        "BaseEntityBlock",
        "getMenuProvider",
        "taken from the block entity",
    ),
    (
        "ComparatorBlock",
        "triggerEvent",
        "forwarded to the block entity, which ignores block events",
    ),
    ("KelpBlock", "canPlaceLiquid", "false, the trait default"),
    ("KelpBlock", "placeLiquid", "false, the trait default"),
    (
        "KelpPlantBlock",
        "canPlaceLiquid",
        "false, the trait default",
    ),
    ("KelpPlantBlock", "placeLiquid", "false, the trait default"),
    (
        "Weathering*",
        "randomTick",
        "`weathering_copper::random_tick` runs for every block with an age, before the behaviour",
    ),
];

/// Hooks that only some declaring classes implement non-trivially (the trait default is the Java answer of every other
/// class): method, the declaring classes that matter.
const ONLY_DECLARERS: &[(&str, &[&str])] = &[(
    "isBonemealSuccess",
    &[
        "AzaleaBlock",
        "MangrovePropaguleBlock",
        "MushroomBlock",
        "NetherFungusBlock",
        "SaplingBlock",
    ],
)];

/// Trait methods an ancestor's override makes no difference for: `is_pathfindable` answers from the extracted state data,
/// `is_valid_bonemeal_target_server` delegates to `is_valid_bonemeal_target` by default.
const REDUNDANT: &[&str] = &["is_pathfindable", "is_valid_bonemeal_target_server"];

fn matches_declarer(pattern: &str, declarer: &str) -> bool {
    pattern
        .strip_suffix('*')
        .map_or(pattern == declarer, |p| declarer.starts_with(p))
}

fn java_overrides() -> Vec<(&'static str, Vec<Override>)> {
    JAVA_OVERRIDES
        .lines()
        .map(|line| {
            let (name, methods) = line.split_once(' ').expect("`name methods` line");
            let methods = if methods == "-" {
                Vec::new()
            } else {
                methods
                    .split(',')
                    .map(|m| m.split_once('@').expect("`method@Class`"))
                    .collect()
            };
            (name, methods)
        })
        .collect()
}

#[test]
fn java_override_fixture_matches_the_registry_and_every_method_is_classified() {
    let java = java_overrides();
    let names: Vec<_> = Block::iter().map(|b| b.data().name).collect();
    assert_eq!(
        java.iter().map(|(n, _)| *n).collect::<Vec<_>>(),
        names,
        "fixtures/block_overrides.txt is stale: regenerate it (see fixtures/BlockOverridesGolden.java)"
    );
    let known: BTreeSet<&str> = HOOKS
        .iter()
        .map(|(j, _)| *j)
        .chain(NO_HOOK.iter().map(|(j, _)| *j))
        .collect();
    let unknown: BTreeSet<_> = java
        .iter()
        .flat_map(|(_, m)| m.iter().map(|(method, _)| *method))
        .filter(|m| !known.contains(m))
        .collect();
    assert!(
        unknown.is_empty(),
        "Java overrides in neither HOOKS nor NO_HOOK: {unknown:?}"
    );
    let rust: BTreeSet<_> = SOURCE.trait_methods.iter().map(String::as_str).collect();
    let bad: Vec<_> = HOOKS
        .iter()
        .flat_map(|(_, r)| r.iter())
        .filter(|r| !rust.contains(*r))
        .collect();
    assert!(
        bad.is_empty(),
        "HOOKS names methods that BlockBehaviour does not have: {bad:?}"
    );
}

/// (b) Every hook the vanilla class chain of a block overrides is overridden by the behaviour the block is bound to.
#[test]
fn bound_behaviours_override_every_hook_of_the_java_chain() {
    let src = &*SOURCE;
    let hooks: BTreeMap<_, _> = HOOKS.iter().copied().collect();
    let mut failures: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for (block, (name, java)) in Block::iter().zip(java_overrides()) {
        let (bound, at) = src.bound(block);
        let own = src.methods(bound);
        for (method, declarer) in java {
            let Some(rust) = hooks.get(method) else {
                continue;
            };
            if GENERIC
                .iter()
                .any(|(d, m, _)| *m == method && matches_declarer(d, declarer))
                || ONLY_DECLARERS
                    .iter()
                    .any(|(m, only)| *m == method && !only.contains(&declarer))
            {
                continue;
            }
            if !rust.iter().any(|r| own.contains(*r)) {
                let class = at.map_or("by name", |i| {
                    block.data().classes.get(i).copied().unwrap_or("none")
                });
                failures
                    .entry(format!(
                        "{method}@{declarer} -> {bound} (registered as {class})"
                    ))
                    .or_default()
                    .push(name.to_string());
            }
        }
    }
    report(
        "Java hooks without a Rust override",
        failures,
        ACCEPTED_HOOKS,
    );
}

fn blocks_where(flag: impl Fn(mc_data::block::BlockState) -> bool) -> Vec<Block> {
    Block::iter().filter(|b| b.states().any(&flag)).collect()
}

fn without(blocks: Vec<Block>, any_of: &[&str]) -> BTreeMap<String, Vec<String>> {
    let src = &*SOURCE;
    let mut failures: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for block in blocks {
        let (bound, _) = src.bound(block);
        let own = src.methods(bound);
        if !any_of.iter().any(|m| own.contains(*m)) {
            failures
                .entry(format!("{bound} lacks {}", any_of.join(" or ")))
                .or_default()
                .push(block.data().name.to_string());
        }
    }
    failures
}

