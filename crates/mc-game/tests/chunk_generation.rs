//! Generation through the chunk status pipeline (worldgen thread, `NoiseWorldGenerator` adapter):
//! * biomes of generated chunks equal the biomes the real vanilla server stored for the same seed (`run/servers/worldref`,
//!   chunks persisted at status `terrain`; features of neighbours do not change biomes);
//! * terrain equals calling `mc_worldgen`'s generator directly (which has its own differential tests against vanilla).
//!   A direct block comparison with vanilla's `terrain`-status chunks is not possible: their neighbours' features
//!   already wrote into them, and structures/features are not generated by the chunk map tests.

use mc_core::ident::Identifier;
use mc_core::pos::ChunkPos;
use mc_game::server::level::worldgen_adapter::NoiseWorldGenerator;
use mc_game::server::level::{ServerLevel, ServerLevelParams};
use mc_game::server::shared::ServerShared;
use mc_nbt::CompoundTag;
use mc_world::chunk::LevelHeight;
use mc_world::palette::PalettedContainerFactory;
use mc_world::region::{RegionFileStorage, RegionStorageInfo};
use mc_world::serial::SerializableChunkData;
use mc_world::status::ChunkStatus;
use mc_worldgen::biome::{BiomeRegistry, biome_source_from_json};
use mc_worldgen::data::{FsDataSource, WorldgenRegistries};
use mc_worldgen::generator::NoiseBasedChunkGenerator;
use mc_worldgen::random_state::RandomState;
use std::path::{Path, PathBuf};
use std::sync::Arc;

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn read_status_chunks(folder: &Path, status: &str) -> Vec<(ChunkPos, CompoundTag)> {
    let mut regions = Vec::new();
    for e in std::fs::read_dir(folder).unwrap() {
        let name = e.unwrap().file_name().into_string().unwrap();
        if let Some(rest) = name.strip_prefix("r.").and_then(|r| r.strip_suffix(".mca")) {
            let (x, z) = rest.split_once('.').unwrap();
            regions.push((x.parse::<i32>().unwrap(), z.parse::<i32>().unwrap()));
        }
    }
    regions.sort();
    let mut storage = RegionFileStorage::new(RegionStorageInfo::new("t", Identifier::parse("minecraft:overworld").unwrap(), "chunk"), folder, false);
    let mut out = Vec::new();
    for (rx, rz) in regions {
        for lz in 0..32 {
            for lx in 0..32 {
                let pos = ChunkPos::new(rx * 32 + lx, rz * 32 + lz);
                if let Some(tag) = storage.read(&pos).unwrap() {
                    if tag.get_string("Status") == Some(status) {
                        out.push((pos, tag));
                    }
                }
            }
        }
    }
    out
}

#[test]
fn generated_chunks_match_vanilla_biomes_and_direct_terrain() {
    let world = root().join("run/servers/worldref/world");
    let region = world.join("dimensions/minecraft/overworld/region");
    if !region.is_dir() {
        eprintln!("run/servers/worldref missing: skipped");
        return;
    }
    let seed = mc_world::level_storage::SavedDataStorage::new(world.join("data"))
        .get(&Identifier::parse("minecraft:world_gen_settings").unwrap())
        .and_then(|t| t.as_compound().and_then(|c| c.get_long("seed")))
        .expect("world_gen_settings.dat has a seed");

    let registries = Arc::new(WorldgenRegistries::new(Arc::new(FsDataSource::new(root().join("ref/src/data")))));
    let biomes = Arc::new(BiomeRegistry::load(&registries).expect("biome registry"));
    let factory = Arc::new(PalettedContainerFactory::create(mc_world::palette::BiomeRegistry::new(biomes.names())).unwrap());
    let biome_source = biome_source_from_json(&serde_json::json!({"type": "minecraft:multi_noise", "preset": "minecraft:overworld"}), &registries, &biomes).unwrap();
    let settings = registries.noise_settings(&Identifier::parse("minecraft:overworld").unwrap()).unwrap();
    let generator = NoiseBasedChunkGenerator::new(biome_source, Arc::new(settings), registries.clone(), biomes.clone()).unwrap();
    let random_state = Arc::new(RandomState::create(registries.clone(), seed, generator.settings()));
    let direct_generator = Arc::new(generator);
    let direct_random_state = random_state.clone();
    let backend = NoiseWorldGenerator::new(direct_generator.clone(), random_state, seed, Identifier::parse("minecraft:noise").ok());

    let expected: Vec<(ChunkPos, CompoundTag)> = read_status_chunks(&region, "minecraft:terrain");
    assert!(!expected.is_empty(), "the world has no chunk persisted at status terrain");
    let sample: Vec<&(ChunkPos, CompoundTag)> = expected.iter().step_by((expected.len() / 8).max(1)).take(8).collect();

    let dir = std::env::temp_dir().join(format!("mc-chunk-gen-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    let (shared, _rx) = ServerShared::new();
    let height = LevelHeight { min_y: -64, height: 384 };
    let mut level = ServerLevel::new(ServerLevelParams {
        shared,
        dimension: Identifier::parse("minecraft:overworld").unwrap(),
        level_id: "gen".into(),
        dimension_dir: dir.clone(),
        level_height: height,
        sea_level: 63,
        has_sky_light: true,
        factory: factory.clone(),
        generator: Arc::new(backend),
        generate_structures: false,
        seed,
        is_known_structure: Arc::new(|_| false),
        view_distance: 10,
        simulation_distance: 10,
        sync_writes: false,
        is_debug: false,
        level_data: Box::new(mc_game::server::level::level_data::PrimaryServerLevelData(mc_game::server::level::level_data::default_world_data())),
    });
    let mut biome_mismatches = Vec::new();
    for (pos, tag) in &sample {
        let parsed = SerializableChunkData::parse(height, &factory, tag).unwrap().unwrap();
        let want: Vec<_> = parsed
            .section_data
            .iter()
            .filter_map(|s| s.chunk_section.as_ref().map(|c| (s.y, c.biomes().to_nbt(&factory.biomes).unwrap())))
            .collect();
        let chunk = level.proto_chunk_blocking(pos.x, pos.z, ChunkStatus::Terrain, true).expect("terrain chunk generated");
        let got: Vec<_> = want
            .iter()
            .map(|(y, _)| {
                let i = chunk.access.level_height.section_index_from_section_y(*y) as usize;
                (*y, chunk.access.sections[i].biomes().to_nbt(&factory.biomes).unwrap())
            })
            .collect();
        if got != want {
            biome_mismatches.push(*pos);
        }
        // Terrain: the pipeline result equals the direct generator call.
        let mut reference = new_biome_chunk(&direct_generator, &direct_random_state, &factory, height, pos.x, pos.z);
        let mut possible = Vec::new();
        let mut neighbours = Vec::new();
        for dz in -1..=1 {
            for dx in -1..=1 {
                let n = new_biome_chunk(&direct_generator, &direct_random_state, &factory, height, pos.x + dx, pos.z + dz);
                n.access.collect_biomes_in_palette(|b| {
                    if !possible.contains(&b) {
                        possible.push(b);
                    }
                });
                neighbours.push(n);
            }
        }
        let resolver = direct_generator.biome_source().create_uncached_resolver(&direct_random_state);
        let biome_manager = mc_worldgen::biome::BiomeManager::new(&*resolver, mc_worldgen::biome::BiomeManager::obfuscate_seed(seed));
        let blender = mc_worldgen::blending::Blender::empty();
        use mc_worldgen::generator::ChunkGenerator;
        direct_generator.build_terrain(
            &mut reference,
            &mc_worldgen::generator::BuildTerrainContext {
                random_state: &direct_random_state,
                blender: &blender,
                structure_starts: &[],
                biome_manager: &biome_manager,
                possible_biomes: Some(&possible),
                carver_biome_cache: None,
            },
        );
        let chunk = level.proto_chunk_blocking(pos.x, pos.z, ChunkStatus::Terrain, true).unwrap();
        for i in 0..chunk.access.sections.len() {
            assert_eq!(
                chunk.access.sections[i].states().to_nbt(&mc_world::palette::BlockStateCodec).unwrap(),
                reference.access.sections[i].states().to_nbt(&mc_world::palette::BlockStateCodec).unwrap(),
                "terrain section {i} of chunk {pos}"
            );
        }
    }
    level.close();
    let _ = std::fs::remove_dir_all(&dir);
    assert!(biome_mismatches.is_empty(), "biomes differ from the vanilla server for chunks {biome_mismatches:?}");
}

/// A chunk with biomes and persisted status `BIOMES` (what `buildTerrain` sees in the pipeline).
fn new_biome_chunk(
    generator: &NoiseBasedChunkGenerator,
    random_state: &Arc<RandomState>,
    factory: &PalettedContainerFactory,
    height: LevelHeight,
    x: i32,
    z: i32,
) -> mc_world::chunk::ProtoChunk {
    use mc_worldgen::generator::ChunkGenerator;
    let mut chunk = mc_world::chunk::ProtoChunk::new(ChunkPos::new(x, z), mc_world::upgrade_data::UpgradeData::EMPTY, height, factory, None);
    generator.create_biomes(random_state, &mc_worldgen::blending::Blender::empty(), &mut chunk);
    chunk.set_persisted_status(ChunkStatus::Biomes);
    chunk
}
