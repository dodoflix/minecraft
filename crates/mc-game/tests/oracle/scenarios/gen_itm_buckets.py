#!/usr/bin/env python3
"""Generates itm_buckets.txt (block-oracle scenario): buckets, mob buckets, glass bottles and water potions used on assorted
blocks, one `note CASE ...` header per case; replayed by tests/golden/item_buckets_golden.rs.
Fixture: scripts/block-oracle.sh itm_buckets

Usage: python3 crates/mc-game/tests/oracle/scenarios/gen_itm_buckets.py crates/mc-game/tests/oracle/scenarios/itm_buckets.txt
Output: the given file (replaced only when generation succeeds)."""
import os
import sys

if sys.argv[1:] in (["-h"], ["--help"]):
    print(__doc__)
    sys.exit(0)
if len(sys.argv) != 2:
    sys.exit(__doc__)

TARGETS = [
    "minecraft:stone", "minecraft:grass_block", "minecraft:water[level=0]", "minecraft:water[level=3]", "minecraft:lava[level=0]",
    "minecraft:lava[level=4]", "minecraft:powder_snow", "minecraft:oak_slab[type=bottom,waterlogged=false]",
    "minecraft:oak_slab[type=top,waterlogged=true]", "minecraft:oak_slab[type=double,waterlogged=false]",
    "minecraft:oak_stairs[facing=north,half=bottom,shape=straight,waterlogged=false]", "minecraft:kelp[age=3]", "minecraft:seagrass",
    "minecraft:oak_fence[north=false,east=false,south=false,west=false,waterlogged=false]",
    "minecraft:chest[facing=north,type=single,waterlogged=false]", "minecraft:cauldron", "minecraft:water_cauldron[level=3]",
    "minecraft:lava_cauldron", "minecraft:powder_snow_cauldron[level=2]", "minecraft:ice", "minecraft:short_grass",
    "minecraft:snow[layers=3]", "minecraft:oak_sign[rotation=0,waterlogged=false]", "minecraft:lily_pad",
    "minecraft:bubble_column[drag=true]", "minecraft:nether_portal[axis=x]", "minecraft:sea_pickle[pickles=2,waterlogged=false]",
]
BUCKETS = ["minecraft:bucket", "minecraft:water_bucket", "minecraft:lava_bucket", "minecraft:powder_snow_bucket", "minecraft:milk_bucket"]
MOB_BUCKETS = ["pufferfish", "salmon", "cod", "tropical_fish", "axolotl", "sulfur_cube", "tadpole"]
MOB_TARGETS = [
    "minecraft:stone", "minecraft:water[level=0]", "minecraft:lava[level=0]", "minecraft:kelp[age=3]", "minecraft:seagrass",
    "minecraft:oak_slab[type=top,waterlogged=true]", "minecraft:cauldron", "minecraft:short_grass",
]
SIDE_TARGETS = [
    "minecraft:stone", "minecraft:water[level=0]", "minecraft:water[level=3]", "minecraft:lava[level=0]", "minecraft:powder_snow",
    "minecraft:oak_slab[type=top,waterlogged=true]", "minecraft:kelp[age=3]", "minecraft:cauldron", "minecraft:water_cauldron[level=3]",
    "minecraft:short_grass", "minecraft:snow[layers=3]", "minecraft:bubble_column[drag=true]",
]
SIDE_BUCKETS = ["minecraft:bucket", "minecraft:water_bucket", "minecraft:lava_bucket", "minecraft:powder_snow_bucket"]
SNEAK_TARGETS = [
    "minecraft:stone", "minecraft:short_grass", "minecraft:snow[layers=3]", "minecraft:kelp[age=3]", "minecraft:water[level=3]",
    "minecraft:lava[level=0]", "minecraft:oak_slab[type=bottom,waterlogged=false]", "minecraft:oak_slab[type=top,waterlogged=true]",
]
POTIONS = ["minecraft:potion", 'minecraft:potion[potion_contents={potion:"minecraft:water"}]',
           'minecraft:potion[potion_contents={potion:"minecraft:swiftness"}]']
MUD_TARGETS = ["minecraft:dirt", "minecraft:coarse_dirt", "minecraft:rooted_dirt", "minecraft:grass_block", "minecraft:mud", "minecraft:stone"]
MUD_FACES = ["up", "down", "north"]
# name -> (game mode, x of the column the player stands on)
PLAYERS = {"Steve": ("survival", 0), "Cre": ("creative", 8), "Adv": ("adventure", 16), "Pack": ("survival", 24)}

out = [
    "# Buckets, mob buckets, glass bottles and water potions (BucketItem.use, MobBucketItem, BottleItem.use, PotionItem.useOn). Every case puts one",
    "# block under the player (or one block ahead for the sideways cases), gives the item and uses it; the dump shows the blocks around, the scheduled",
    "# ticks, the inventory, the item statistics and the sounds. Pack carries stacks of several buckets, so the emptied container goes to another slot.",
    "# The trailing case number of every use line is ignored by both drivers: entities created by a command draw their random seeds (and UUIDs)",
    "# from the command line text, so equal lines would create entities with equal UUIDs and the second one would be refused.",
    "# generated by gen_itm_buckets.py",
    "level flat",
    "preload 2",
    "difficulty normal",
]
for name, (mode, x) in PLAYERS.items():
    out.append(f"spawn_player {name} {mode} {x}.5 -60 0.5 0 90")
out.append("tick 1")
out.append("dump events")

n = 0


def short(item):
    return item.split("[")[0].split(":")[1]


def case(who, label, item, count, setup, action, cleanup, extra_dump=""):
    """One case: `setup` lines, give, `action` lines, dump, `cleanup` lines."""
    global n
    x = PLAYERS[who][1]
    out.append(f"note CASE {n} who={who} {label}")
    out.append(f"level_seed {n + 1}")
    out.extend(setup)
    out.append(f"give {who} mainhand {item} {count}")
    out.extend(action)
    out.append(f"dump blocks:{x},-61,0,{x},-59,2 ticks:{x},-61,0,{x},-59,2 inventory:{who} stats:{who} {extra_dump}events")
    out.extend(cleanup)
    out.append(f"give {who} mainhand minecraft:air")
    n += 1


def down(who, label, item, target, count=1, sneak=False, extra_dump=""):
    x = PLAYERS[who][1]
    setup = [f"block {x} -61 0 {target}", f"block {x} -60 0 minecraft:air"]
    action = [f"use {who} main {n}"]
    cleanup = [f"block {x} -60 0 minecraft:air", f"block {x} -61 0 minecraft:grass_block"]
    if sneak:
        setup.append(f"input {who} sneak")
        cleanup.append(f"input {who} none")
    case(who, f"{label} target={target}", item, count, setup, action, cleanup, extra_dump)


def side(who, label, item, target):
    x = PLAYERS[who][1]
    setup = [f"snap {who} {x}.5 -60 0.5 0 0", f"block {x} -59 2 {target}", f"block {x} -59 1 minecraft:air"]
    cleanup = [f"block {x} -59 2 minecraft:air", f"block {x} -59 1 minecraft:air", f"snap {who} {x}.5 -60 0.5 0 90"]
    case(who, f"{label} sideways target={target}", item, 1, setup, [f"use {who} main {n}"], cleanup)


# every container item straight down on every target, survival / creative / adventure
for who in ("Steve", "Cre"):
    for item in BUCKETS + ["minecraft:glass_bottle"]:
        for target in TARGETS:
            down(who, f"item={short(item)}", item, target)
for item in ["minecraft:bucket", "minecraft:water_bucket", "minecraft:lava_bucket", "minecraft:glass_bottle"]:
    for target in TARGETS:
        down("Adv", f"item={short(item)}", item, target)

# mob buckets keep their entities; dumped each time (a bucket that cannot empty spawns nothing)
for who in ("Steve", "Cre"):
    for mob in MOB_BUCKETS:
        for target in MOB_TARGETS:
            down(who, f"item={mob}_bucket", f"minecraft:{mob}_bucket", target, extra_dump="entities ")

# stacks of buckets and bottles: the emptied / filled container goes to the inventory
for item, count in [("minecraft:bucket", 3), ("minecraft:glass_bottle", 3), ("minecraft:water_bucket", 2)]:
    for target in ["minecraft:stone", "minecraft:water[level=0]", "minecraft:lava[level=0]", "minecraft:powder_snow", "minecraft:kelp[age=3]"]:
        down("Pack", f"item={short(item)} count={count}", item, target, count=count)

# off hand
for item in ["minecraft:bucket", "minecraft:water_bucket", "minecraft:lava_bucket", "minecraft:glass_bottle", "minecraft:axolotl_bucket"]:
    for target in ["minecraft:stone", "minecraft:water[level=0]", "minecraft:kelp[age=3]"]:
        x = 0
        out.append(f"note CASE {n} who=Steve item={short(item)} offhand target={target}")
        out.append(f"level_seed {n + 1}")
        out += [f"block {x} -61 0 {target}", f"block {x} -60 0 minecraft:air", "give Steve mainhand minecraft:stick", f"give Steve offhand {item}", f"use Steve off {n}"]
        out.append(f"dump blocks:{x},-61,0,{x},-59,2 ticks:{x},-61,0,{x},-59,2 inventory:Steve stats:Steve entities events")
        out += [f"block {x} -60 0 minecraft:air", f"block {x} -61 0 minecraft:grass_block", "give Steve offhand minecraft:air", "give Steve mainhand minecraft:air"]
        n += 1

# sneaking: a replaceable or waterloggable block is not filled
for who in ("Steve", "Cre"):
    for item in ["minecraft:water_bucket", "minecraft:lava_bucket", "minecraft:powder_snow_bucket", "minecraft:bucket"]:
        for target in SNEAK_TARGETS:
            down(who, f"item={short(item)} sneaking", item, target, sneak=True)

# looking at the side of a block
for who in ("Steve", "Cre"):
    for item in SIDE_BUCKETS:
        for target in SIDE_TARGETS:
            side(who, f"item={short(item)}", item, target)
for target in SIDE_TARGETS:
    side("Steve", "item=glass_bottle", "minecraft:glass_bottle", target)

# water potions on mud-convertible blocks (`PotionItem.useOn`); the clicked face is part of the case
for who in ("Steve", "Cre"):
    for item in POTIONS:
        for target in MUD_TARGETS:
            for face in MUD_FACES:
                x = PLAYERS[who][1]
                setup = [f"block {x} -61 0 {target}", f"block {x} -60 0 minecraft:air"]
                cleanup = [f"block {x} -61 0 minecraft:grass_block"]
                case(who, f"item={item} face={face} target={target}", item, 1, setup, [f"use_on {who} {x} -61 0 {face} main"], cleanup)
for face in MUD_FACES:
    who, x = "Adv", 16
    item = 'minecraft:potion[potion_contents={potion:"minecraft:water"}]'
    case(who, f"item=water_potion face={face} target=dirt", item, 1,
         [f"block {x} -61 0 minecraft:dirt"], [f"use_on {who} {x} -61 0 {face} main"], [f"block {x} -61 0 minecraft:grass_block"])

path = sys.argv[1]
tmp = path + ".tmp"
with open(tmp, "w") as f:
    f.write("\n".join(out) + "\n")
os.replace(tmp, path)
print(f"{n} cases", file=sys.stderr)
