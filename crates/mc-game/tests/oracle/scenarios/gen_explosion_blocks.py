#!/usr/bin/env python3
"""Generates explosion_blocks.txt (scenario of the entity oracle): random terrain boxes + Level.explode, dumps the blocks left.
Run: python3 gen_explosion_blocks.py > explosion_blocks.txt ; scripts/entity-oracle.sh explosion_blocks.txt -o ../../fixtures/entity_oracle/explosion_blocks.txt
Replayed by tests/golden/explosion_golden.rs."""
import math
POOL = ["minecraft:stone"] * 6 + ["minecraft:dirt", "minecraft:obsidian", "minecraft:water[level=0]", "minecraft:lava[level=0]", "minecraft:glass",
        "minecraft:sand", "minecraft:oak_planks", "minecraft:gravel", "minecraft:bedrock", "minecraft:air", "minecraft:air", "minecraft:cobblestone",
        "minecraft:water[level=3]", "minecraft:iron_block", "minecraft:netherrack"]
def pool_for(tseed):
    # lava next to water turns into obsidian/cobblestone by the fluid blocks' neighbor reaction (not an explosion matter): never mix them
    bad = "water" if tseed % 2 == 0 else "lava"
    return [b if bad not in b else "minecraft:stone" for b in POOL]
def h(x, y, z, s):
    v = (x * 73856093) ^ (y * 19349663) ^ (z * 83492791) ^ (s * 2654435761)
    v &= 0xFFFFFFFF
    v ^= v >> 15; v = (v * 0x2c1b3c6d) & 0xFFFFFFFF; v ^= v >> 12; v = (v * 0x297a2d39) & 0xFFFFFFFF; v ^= v >> 15
    return v
# (cx, cy, cz, radius, fire, interaction, level seed, terrain seed)
CASES = [(0, 0, 0, 1.0, 0, "block", 1, 1), (0.5, 0.5, 0.5, 2.0, 0, "block", 2, 2), (3.3, 1.7, -2.2, 3.0, 0, "mob", 3, 3), (0, 0, 0, 4.0, 1, "tnt", 4, 4),
         (0.5, 0.0625, 0.5, 4.0, 0, "tnt", 5, 5), (1.5, 2.5, 1.5, 5.0, 1, "block", 6, 6), (0, 0, 0, 6.0, 0, "mob", 7, 7), (0.5, 0.5, 0.5, 7.0, 0, "block", 8, 8),
         (0, 0, 0, 10.0, 1, "block", 9, 9), (0.5, -62.0, 0.5, 5.0, 0, "tnt", 10, 10), (0, 0, 0, 3.0, 0, "none", 11, 11), (0.5, 0.5, 0.5, 4.0, 0, "trigger", 12, 12),
         (2.0, 0.0, 2.0, 0.5, 0, "block", 13, 13), (0, 0, 0, 8.0, 0, "tnt", 14, 14)]
print("# generated by gen_explosion_blocks.py: terrain boxes + Level.explode, dump of the blocks left")
print("level void")
for (cx, cy, cz, r, fire, inter, lseed, tseed) in CASES:
    POOL_C = pool_for(tseed)
    e = int(math.ceil(r * 1.3)) + 3
    x0, y0, z0 = int(math.floor(cx)) - e, max(int(math.floor(cy)) - e, -64), int(math.floor(cz)) - e
    x1, y1, z1 = int(math.floor(cx)) + e, int(math.floor(cy)) + e, int(math.floor(cz)) + e
    print(f"note case {cx} {cy} {cz} r={r} fire={fire} {inter}")
    for x in range(x0, x1 + 1):
        for z in range(z0, z1 + 1):
            y = y0
            while y <= y1:
                s = POOL_C[h(x // 2, y // 2, z // 2, tseed) % len(POOL_C)] if h(x, y, z, tseed + 100) % 5 else POOL_C[h(x, y, z, tseed) % len(POOL_C)]
                y2 = y
                while y2 + 1 <= y1 and (POOL_C[h(x // 2, (y2 + 1) // 2, z // 2, tseed) % len(POOL_C)] if h(x, y2 + 1, z, tseed + 100) % 5 else POOL_C[h(x, y2 + 1, z, tseed) % len(POOL_C)]) == s:
                    y2 += 1
                if s != "minecraft:air":
                    print(f"fill {x} {y} {z} {x} {y2} {z} {s}")
                y = y2 + 1
    print(f"level_seed {lseed}")
    print(f"explode {cx} {cy} {cz} {r}" + (" fire" if fire else "") + f" {inter}")
    print(f"dump blocks:{x0},{y0},{z0},{x1},{y1},{z1}")
    print(f"fill {x0} {y0} {z0} {x1} {y1} {z1} minecraft:air")
