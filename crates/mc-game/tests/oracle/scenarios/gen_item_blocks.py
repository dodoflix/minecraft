#!/usr/bin/env python3
"""Generates item_blocks.txt (entity-oracle scenario): axes/hoes/shovels (block_transformer) and honeycomb on blocks, one
`note CASE ...` header per case; replayed by tests/golden/item_blocks_golden.rs.
Run: python3 gen_item_blocks.py > item_blocks.txt ; scripts/entity-oracle.sh crates/mc-game/tests/oracle/scenarios/item_blocks.txt -o crates/mc-game/tests/fixtures/entity_oracle/item_blocks.txt"""
import json, os
D = os.path.join(os.path.dirname(__file__), "../../../../../ref/src/data/minecraft/block_transformer")
axe = json.load(open(os.path.join(D, "axe.json")))
axe_blocks = []
for t in axe:
    sp = t["block_state_provider"]
    for r in sp.get("rules", []):
        b = r["if_true"]["blocks"]
        axe_blocks.append(b)
cases = []  # (tool, block state, above, face)
for b in axe_blocks:
    cases.append(("minecraft:iron_axe", b, None, "up"))
for b in ["minecraft:stone", "minecraft:oak_planks", "minecraft:grass_block", "minecraft:air"]:
    cases.append(("minecraft:iron_axe", b, None, "up"))
cases.append(("minecraft:iron_axe", "minecraft:oak_log[axis=z]", None, "north"))
cases.append(("minecraft:wooden_axe", "minecraft:crimson_stem[axis=y]", None, "down"))
for b in ["minecraft:grass_block", "minecraft:dirt", "minecraft:podzol", "minecraft:mycelium", "minecraft:coarse_dirt", "minecraft:rooted_dirt", "minecraft:farmland[moisture=3]", "minecraft:dirt_path", "minecraft:stone"]:
    for above in (None, "minecraft:stone", "minecraft:short_grass"):
        cases.append(("minecraft:iron_shovel", b, above, "up"))
        cases.append(("minecraft:iron_hoe", b, above, "up"))
    cases.append(("minecraft:iron_shovel", b, None, "down"))
    cases.append(("minecraft:iron_hoe", b, None, "down"))
    cases.append(("minecraft:iron_hoe", b, None, "north"))
for b in ["minecraft:copper_block", "minecraft:exposed_cut_copper", "minecraft:weathered_cut_copper_slab[type=top]", "minecraft:oxidized_copper_bulb[lit=true]", "minecraft:copper_door[half=lower,facing=east,hinge=right,open=true,powered=false]",
          "minecraft:exposed_copper_chest[facing=north,type=single,waterlogged=false]", "minecraft:waxed_copper_block", "minecraft:oxidized_copper", "minecraft:lightning_rod[facing=up,powered=false,waterlogged=false]",
          "minecraft:copper_trapdoor[half=top,open=false,powered=false,waterlogged=false,facing=south]", "minecraft:weathered_copper_golem_statue[facing=east,waterlogged=false,copper_golem_pose=standing]", "minecraft:stone", "minecraft:copper_chain[axis=y,waterlogged=false]",
          "minecraft:waxed_oxidized_copper_lantern[hanging=true,waterlogged=false]"]:
    cases.append(("minecraft:honeycomb", b, None, "up"))
print("# generated by gen_item_blocks.py")
print("level flat")
print("spawn_player Steve survival 0.5 -60 0.5 0 0")
print("move_packet Steve 0.5 -60 0.5 true")
print("level_seed 12345")
for i, (tool, b, above, face) in enumerate(cases):
    print(f"note CASE {i} tool={tool.split(':')[1]} block={b.replace(' ', '')} above={above or 'none'} face={face}")
    print(f"block 2 -60 0 {b}")
    print(f"block 2 -59 0 {above or 'minecraft:air'}")
    print(f"give Steve mainhand {tool}")
    print(f"use_on Steve 2 -60 0 {face}")
    print("dump blocks:2,-60,0,2,-59,0 inventory:Steve entities")
    print("block 2 -60 0 minecraft:air")
    print("block 2 -59 0 minecraft:air")
    print("cmd kill @e[type=item]")
