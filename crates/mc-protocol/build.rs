//! Generates `ids.rs`: packet id constants per (state, flow) from vanilla's `packets.json` report.
use std::{collections::BTreeMap, env, fmt::Write, fs, path::PathBuf};

fn main() {
    let path = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap())
        .join("../../ref/generated/reports/packets.json");
    println!("cargo:rerun-if-changed={}", path.display());
    let text = fs::read_to_string(&path).unwrap_or_else(|_| {
        panic!("{} is missing: run scripts/setup-ref.sh (builds the gitignored ref/ reference material)", path.display())
    });
    let json: serde_json::Value = serde_json::from_str(&text).expect("packets.json is JSON");
    let mut out = String::from("// @generated by build.rs from the packets.json report\n");
    for (state, flows) in json.as_object().expect("object") {
        writeln!(out, "pub mod {state} {{").unwrap();
        for (flow, packets) in flows.as_object().expect("object") {
            writeln!(out, "    pub mod {flow} {{").unwrap();
            let mut by_id = BTreeMap::new();
            for (name, p) in packets.as_object().expect("object") {
                let id = p["protocol_id"].as_i64().expect("protocol_id");
                let short = name.strip_prefix("minecraft:").expect("minecraft: prefix");
                let konst = short.replace('/', "_").to_uppercase();
                writeln!(out, "        pub const {konst}: i32 = {id};").unwrap();
                by_id.insert(id, name.clone());
            }
            writeln!(out, "        /// `(id, resource name)` sorted by id.").unwrap();
            writeln!(out, "        pub const NAMES: &[(i32, &str)] = &[").unwrap();
            for (id, name) in by_id {
                writeln!(out, "            ({id}, {name:?}),").unwrap();
            }
            writeln!(out, "        ];\n    }}").unwrap();
        }
        writeln!(out, "}}").unwrap();
    }
    fs::write(
        PathBuf::from(env::var("OUT_DIR").unwrap()).join("ids.rs"),
        out,
    )
    .unwrap();
}
